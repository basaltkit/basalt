/** Both catalogs, for the test that keeps their keys and placeholders in step. */
export const CATALOGS: Record<Locale, Record<MessageKey, MessageValue>> = { en, pt }

let current: Locale = 'en'
let languages: readonly string[] = []

/** The page's language from now on; views read it at render time, so a re-render switches in place. */
export function setLocale(locale: Locale, browserLanguages: readonly string[] = languages): void {
  current = locale
  languages = browserLanguages
}

export const getLocale = (): Locale => current

export const isLocale = (value: unknown): value is Locale => value === 'en' || value === 'pt'

/** The saved choice, else the browser's first language the page speaks, else English. */
export function pickLocale(saved: unknown, browserLanguages: readonly string[] = []): Locale {
  if (isLocale(saved)) return saved
  for (const language of browserLanguages) {
    const base = language.toLowerCase().split('-')[0]
    if (isLocale(base)) return base
  }
  return 'en'
}

/** For dates: the browser's own variant of the page's language (pt-AO, en-GB…), else the bare one. */
export function formatLocale(): string {
  const own = languages.find((l) => l.toLowerCase().split('-')[0] === current)
  if (own) {
    try {
      if (Intl.getCanonicalLocales(own).length > 0) return own
    } catch {
      // Not a BCP-47 tag: the bare language.
    }
  }
  return current
}

/**
 * The plural rules the catalogs are written for: the Portuguese one is
 * European (as in Angola: "0 avisos"), whatever variant the browser names.
 */
const PLURALS: Record<Locale, string> = { en: 'en', pt: 'pt-PT' }

/** A message in the page's language: `{param}` filled in, plural forms picked by `count`. */
export function t(key: MessageKey, params: Record<string, unknown> = {}): string {
  return render(CATALOGS[current][key], PLURALS[current], params)
}

/** Why a commit list is missing, in fixed local text: the server's wording never reaches the page. */
export function reasonText(reason: unknown): string {
  return typeof reason === 'string' && Object.hasOwn(en, `reason.${reason}`) && reason !== 'none'
    ? t(`reason.${reason as CommitsUnavailable}`)
    : t('reason.none')
}

