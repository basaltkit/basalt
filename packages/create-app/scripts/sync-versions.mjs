// Regenerates src/versions.ts from the workspace package.json versions, so a
// freshly scaffolded app depends on the CURRENT release line of every
// @basaltkit/* package it uses (a hardcoded `^1.0.0` once pinned new apps to
// frozen 1.x lines that miss later security fixes). Runs before every build;
// tests/security.test.ts fails if the committed map drifts from the workspace.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const packagesDir = join(here, '..', '..')
const target = join(here, '..', 'src', 'versions.ts')

/** Every package of this repo the templates (API + web UI) can emit. */
const SCAFFOLDED = [
  '@basaltkit/admin',
  '@basaltkit/admin-shadcn',
  '@basaltkit/ai-mcp',
  '@basaltkit/auth',
  '@basaltkit/auth-prisma',
  '@basaltkit/cli',
  '@basaltkit/config',
  '@basaltkit/core',
  '@basaltkit/deploy',
  '@basaltkit/env',
  '@basaltkit/events',
  '@basaltkit/fastify',
  '@basaltkit/generator',
  '@basaltkit/logger',
  '@basaltkit/mailer',
  '@basaltkit/mcp',
  '@basaltkit/prisma',
  '@basaltkit/sdk',
  '@basaltkit/subscriptions',
  '@basaltkit/subscriptions-prisma',
  '@basaltkit/teams',
  '@basaltkit/teams-prisma',
  '@basaltkit/tenancy',
  '@basaltkit/tenancy-prisma',
  '@basaltkit/testing',
  // Not a framework package: the scaffold's devDependency that serves
  // `pnpm basalt update | add | doctor | info`.
  'create-basalt',
]

const versions = new Map()
for (const entry of readdirSync(packagesDir)) {
  try {
    const pkg = JSON.parse(readFileSync(join(packagesDir, entry, 'package.json'), 'utf8'))
    if (typeof pkg.name === 'string' && typeof pkg.version === 'string') versions.set(pkg.name, pkg.version)
  } catch {
    // not a package directory
  }
}

const lines = SCAFFOLDED.map((name) => {
  const version = versions.get(name)
  if (!version) throw new Error(`sync-versions: ${name} not found in the workspace`)
  // The full version, not `^<major>.<minor>.0`: a patch can carry the ranges
  // that make it work with the rest of the scaffold (a dependent patch after a
  // sibling's major), and a `.0` floor would let a new app resolve the older
  // patch of the same line.
  return `  '${name}': '^${version}',`
})

const content = `// GENERATED by scripts/sync-versions.mjs (runs before every build) — do not edit.
// The dependency range a new app gets for each @basaltkit/* package: the
// workspace version as the floor (^<major>.<minor>.<patch>), so a new app never
// resolves an older patch of the same line.
export const SCAFFOLD_VERSIONS: Readonly<Record<string, string>> = {
${lines.join('\n')}
}
`
writeFileSync(target, content)
